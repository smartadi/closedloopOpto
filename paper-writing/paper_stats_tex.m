function paper_stats_tex(outFile)
% PAPER_STATS_TEX  Write the manuscript's "Statistical tables" section from saved outputs.
%   paper_stats_tex                      % -> ../Closedloop_edit/stat_tables.tex
%   paper_stats_tex(outFile)
% Reads ONLY paper-writing/STATS_TABLE.csv (run paper_stats_table first) and
% data/fig2b_trial_counts.csv (impulse-analysis/f2b_trial_counts.m). No number in the
% tables is typed by hand, except the per-state trial counts of Fig 4D (see N4D below).
% Layout (2026-10-16, user: "clean and readable"): one table per figure, long format,
% booktabs rules only, effect and CI in one column, p to 2 significant figures.
root = fileparts(fileparts(mfilename('fullpath')));
if nargin < 1
    outFile = fullfile(fileparts(root), 'Closedloop_edit', 'stat_tables.tex');
end
opts = detectImportOptions(fullfile(root,'paper-writing','STATS_TABLE.csv'), 'TextType','string', ...
              'Delimiter', ',');
opts = setvartype(opts, intersect({'role','sessions_agree','mice_agree'}, opts.VariableNames), 'string');
T = readtable(fullfile(root,'paper-writing','STATS_TABLE.csv'), opts);
C = readtable(fullfile(root,'data','fig2b_trial_counts.csv'), 'TextType','string');
if isdatetime(C.date), C.date = string(C.date, 'yyyy-MM-dd'); end
R = @(id) T(T.id == id, :);

L = {};
add('% =============================================================================');
add('% stat_tables.tex -- GENERATED by brain_paper/paper-writing/paper_stats_tex.m');
add(sprintf('%% from STATS_TABLE.csv on %s. Do not edit by hand: re-run the generator.', ...
                datestr(now,'yyyy-mm-dd')));
add('% =============================================================================');
add('\section*{Statistical tables}');
add('\label{sec:stat_tables}');
add(['Every statistic quoted in the Results is listed here with its estimate, ' ...
         '95\% confidence interval, test statistic, $p$-value and $n$. Tests are described ' ...
         'in Materials and Methods (\nameref{sec:stats}). $p$-values are two-sided and ' ...
         'uncorrected unless stated.']);
add('');

% ---------------- Table: Fig 2B/2G trial counts --------------------------------------------
% One row per session (2026-10-20, user: "compress table 2"): amplitudes listed, trials per
% amplitude as a range. The per-amplitude counts stay in data/fig2b_trial_counts.csv.
add('\begin{table}[!ht]', '\centering', '\small', ...
        '\caption{\textbf{Impulse-response trials per session} (Figure~\ref{fig:figure2}B and G). Amplitudes, the nonzero stimulation amplitudes, all of which were analyzed. Trials, trials with a valid evoked-suppression value, per amplitude (range across amplitudes) and in total.}', ...
        '\label{tab:stat_counts}', ...
        '\begin{tabular}{lllcr}', '\toprule', ...
        'Session & Date & Amplitudes (mW) & Trials per amplitude & Total \\', '\midrule');
[us,~,is] = unique(C.label, 'stable');
for s = 1:numel(us)
    k = find(is == s);
    r = C(k(1),:);
    amps = strjoin(arrayfun(@(a) sprintf('%.2f', a), C.amp_mW(k), 'UniformOutput', false), ', ');
    nlo = min(C.n(k));  nhi = max(C.n(k));
    if nlo == nhi, ns = sprintf('%d', nlo); else, ns = sprintf('%d--%d', nlo, nhi); end
    add(sprintf('%s & %s & %s & %s & %d \\\\', char(r.label), strrep(char(r.date),'_','\_'), ...
        amps, ns, sum(C.n(k))));
end
add('\midrule', sprintf('All sessions & & & & %d \\\\', sum(C.n)), ...
        '\bottomrule', '\end{tabular}', '\end{table}', '');

% ---------------- Table: Fig 2G state dependence of impulse-response variability ------------
add('\begin{table}[!ht]', '\centering', '\small', ...
        '\caption{\textbf{Single-trial impulse-response variability and pre-stimulus state} (Figure~\ref{fig:figure2}G and Figure~\ref{fig:state_quartile}; 4 sessions, 3 mice, 1516 trials). Figure~\ref{fig:figure2} is reported descriptively; the slope tests below are supporting and are not used for inference in the text. Ratio, variability in the top versus bottom within-session quartile of the state, computed in each session; geometric mean across sessions, with the range of the four per-session ratios in parentheses (with four sessions we give the range rather than a confidence interval). Slope, per-session slope of variability on state, one-sample $t$-test across sessions (3 degrees of freedom); agreeing, sessions with the same sign. Stimulus-free, the same measures in the stimulus-free window. $\rho$, Spearman correlation over pooled trials (descriptive; no test). Bonferroni threshold for three states, $p < 0.017$.}', ...
        '\label{tab:stat_fig2g}', ...
        '\begin{tabular}{lccccccc}', '\toprule', ...
        ' & \multicolumn{4}{c}{Stimulus response} & & \multicolumn{2}{c}{Stimulus-free} \\', ...
        '\cmidrule(lr){2-5} \cmidrule(lr){7-8}', ...
        'State & Ratio (range) & $t(3)$ & $p$ & Agreeing & $\rho$ & Ratio (range) & $\rho$ \\', '\midrule');
st2 = {'MOT','Motion'; 'DPr','Relative 2--4\,Hz'; 'DPa','Absolute 2--4\,Hz'};
for i = 1:size(st2,1)
    ra = R("2G_"+st2{i,1}+"_ratio"); sl = R("2G_"+st2{i,1}+"_slope");
    rh = R("2G_"+st2{i,1}+"_rho");   cr = R("2G_"+st2{i,1}+"_ctrlratio"); ch = R("2G_"+st2{i,1}+"_ctrl");
    ag = regexp(sl.claim, '\((\d+/\d+) sessions agree\)', 'tokens', 'once');
    add(sprintf('%s & %s & %s & %s & %s & %s & %s & %s \\\\', st2{i,2}, ...
        estrng(ra.effect, ra.ci_lo, ra.ci_hi), num(sl.stat), pvm(sl.p), ag{1}, ...
        num(rh.effect), estrng(cr.effect, cr.ci_lo, cr.ci_hi), num(ch.effect)));
end
sp = R("2G_ctl_resp_spread");
% Response against its stimulus-free control (Supplementary state-quartile figure): top quartile
% vs the mean of the other three, on the per-session response/control ratio.
bc = arrayfun(@(i) R("2G_"+st2{i,1}+"_beyondctrl"), 1:size(st2,1), 'UniformOutput', false);
sc = arrayfun(@(i) R("2G_"+st2{i,1}+"_stimctrl"),   1:size(st2,1), 'UniformOutput', false);
lc = @(nm) [lower(nm(1)) nm(2:end)];
scS = strjoin(cellfun(@(b,nm) sprintf('%s %s', lc(nm), estrng(b.effect, b.ci_lo, b.ci_hi)), ...
                      sc, st2(:,2).', 'UniformOutput', false), ', ');
bcS = strjoin(cellfun(@(b,nm) sprintf('%s $p = %s$', lc(nm), pv(b.p)), ...
                      bc, st2(:,2).', 'UniformOutput', false), ', ');
add('\bottomrule', '\end{tabular}', ...
        sprintf(['\\par\\smallskip\\parbox{\\linewidth}{\\footnotesize Stimulus-free versus response within-session variability: median ratio %s, range %s--%s across sessions. ' ...
                 'Response relative to stimulus-free variability, top versus bottom quartile (geometric mean, range): %s. ' ...
                 'Supporting test, top quartile of this ratio versus the mean of the other three (one-sample $t$-test on per-session log ratios, 3 degrees of freedom): %s.}'], ...
                num(sp.effect), num(sp.ci_lo), num(sp.ci_hi), scS, bcS), ...
        '\end{table}', '');

% ---------------- Table: Fig 3 OL vs CL ------------------------------------------------------
% SESSION RULE (2026-10-27, STATS_AUDIT §7): one test, the two-sided one-sample t on the per-session
% log ratios (df 14), with the exact Wilcoxon, sessions (mice) below one and the leave-one-mouse-out
% worst p as columns. 0-3 s is the primary window. Pre/post are controls: ratio + CI, no test.
add('\begin{table}[!ht]', '\centering', '\small', ...
        '\caption{\textbf{Closed- versus open-loop tracking error and trial-to-trial variability} (Figure~\ref{fig:figure3}; 15 sessions, 4 mice, 1670 trials). Ratio, per-session ratio of the closed- to the open-loop value (mean per-trial RMSE, or across-trial variance averaged over the window), so that below one means closed loop was better; geometric mean across sessions with its $t$-based 95\% CI. Lower, $100\,(1-\mathrm{ratio})$. $t$ and $p$, two-sided one-sample $t$-test of the per-session log ratios (14 degrees of freedom); Wilcoxon, exact signed-rank test on the same values. Below one, sessions with a ratio below one (in parentheses, mice whose mean log ratio is below zero). LOMO, the largest $p$ of the $t$-test when each mouse is left out in turn. The pre- and post-stimulation windows are controls and are reported as the ratio with its CI, without a test. Post-stimulation window, 1\,s (RMSE, the end of the stored trial segment) or 3\,s (variance) after offset.}', ...
        '\label{tab:stat_fig3}', ...
        '\begin{tabular}{lccccccc}', '\toprule', ...
        'Window & Ratio [95\% CI] & Lower & $t$ & $p$ & Wilcoxon $p$ & Below one & LOMO $p$ \\', '\midrule');
win = {'pre','Pre-stimulation'; 'early','0--1\,s'; 'late','1--3\,s'; 'full','0--3\,s$^{a}$'; 'post','Post-stimulation'};
blk = {'3H','rmse','Tracking RMSE'; '3I','var','Across-trial variance'};
for b = 1:2
    add(sprintf('\\multicolumn{8}{l}{\\textit{%s}} \\\\', blk{b,3}));
    for w = 1:size(win,1)
        add(f3row(['\quad ' win{w,2}], R(blk{b,1}+"_"+blk{b,2}+"_"+win{w,1})));
    end
    if b == 1, add('\addlinespace'); end
end
% Review M1 (2026-10-20): CL against the best fixed OL input (ctrl_best_fixed_ol.m), same columns.
add('\addlinespace', '\multicolumn{8}{l}{\textit{Tracking RMSE, closed loop / best fixed input}$^{b}$} \\');
wb = {'early','0--1\,s'; 'late','1--3\,s'; 'full','0--3\,s$^{a}$'};
for w = 1:size(wb,1)
    add(f3row(['\quad ' wb{w,2}], R("3H_best_"+wb{w,1})));
end
cs = R("3H_best_cstar");  rh = R("3H_best_cmd_rho");
add('\bottomrule', '\end{tabular}', ...
        sprintf(['\\par\\smallskip\\parbox{\\linewidth}{\\footnotesize $^{a}$Primary window; 0--1 and 1--3\\,s are its transient and steady-state parts. ' ...
                 '$^{b}$Open-loop RMSE recomputed for the fixed input that minimizes it, under the linear model and on the same trials, which favors open loop (Materials and Methods). ' ...
                 'The best fixed input was a median of %s times the open-loop input (interquartile range %s--%s), and the mean closed-loop command over 1--3\\,s, relative to the open-loop command, was correlated with it across sessions (Spearman $\\rho = %s$, $p = %s$, %d sessions).}'], ...
                num(cs.effect,'%.2f',false), num(cs.ci_lo,'%.2f',false), num(cs.ci_hi,'%.2f',false), ...
                num(rh.effect,'%.2f',false), pv(rh.p), rh.n), ...
        '\end{table}', '');

% ---------------- Table: Fig 4D state dependence ---------------------------------------------
% SESSION RULE (user 2026-10-27): per-session OLS slopes on the within-session standardized state,
% one-sample t across sessions. p = uncorrected (the figure stars, each P/R/A its own question);
% Holm p within P+R (8 tests) and within A (4 tests). Gap and gap trend are descriptive.
% Trial counts per state (not in STATS_TABLE): 1670 trials; 1190 for motion (face video in 11 sessions).
N4D = struct('initdev',1670,'motion',1190,'delta',1670,'absdelta',1670);
add('\begin{table}[!ht]', '\centering', '\small', ...
        '\caption{\textbf{State dependence of open- and closed-loop tracking error} (Figure~\ref{fig:figure4}D). In each session, ordinary least-squares slopes of per-trial RMSE from 1 to 3\,s after onset on the state, standardized within session; slopes in $\%\,\Delta F/F$ of RMSE per within-session SD of the state, tested across sessions with a two-sided one-sample $t$-test (Materials and Methods). Gap, open- minus closed-loop mean RMSE (descriptive; the Figure~\ref{fig:figure3} result). Predictability and regularizability, open- and closed-loop slopes. Attenuation, closed- minus open-loop slope of $\log$ RMSE, given as the percent change per SD of the closed-to-open-loop RMSE ratio; negative, the loop removes a larger fraction of the open-loop error. Gap trend, open- minus closed-loop slope (not interpreted; Materials and Methods). $p$, uncorrected, as marked in Figure~\ref{fig:figure4}D; Holm $p$, Holm-adjusted within predictability and regularizability (eight tests) and within attenuation (four tests). Sessions, sessions whose estimate has the sign of the mean.}', ...
        '\label{tab:fig4_state_stats}', ...
        '\setlength{\tabcolsep}{4pt}', ...   % six columns overran the text width by 15 pt at the default 6 pt
        '\begin{tabular}{llcccc}', '\toprule', ...
        'State & Quantity & Estimate [95\% CI] & Test & Holm $p$ & Sessions \\', '\midrule');
st4 = {'initdev','Initial deviation'; 'motion','Motion'; 'delta','Relative 2--4\,Hz'; 'absdelta','Absolute 1--4\,Hz'};
qs  = {'gap','Gap'; 'pred','Predictability'; 'reg','Regularizability'; 'att','Attenuation (\% per SD)'; 'gaptrend','Gap trend'};
for i = 1:size(st4,1)
    for q = 1:size(qs,1)
        g = R("4D_"+st4{i,1}+"_"+qs{q,1});
        if q == 1
            c1 = st4{i,2};
        elseif q == 2
            c1 = sprintf('\\footnotesize %d sessions, %d trials', g.n, N4D.(st4{i,1}));
        else
            c1 = '';
        end
        if strcmp(qs{q,1}, 'att'), e = pctci(g.effect, g.ci_lo, g.ci_hi);
        else,                      e = estci(g.effect, g.ci_lo, g.ci_hi, true); end
        if strcmp(qs{q,1}, 'gap'), tst = '---';
        else, tst = sprintf('$t(%s) = %s$, $p = %s$', dfs(g.df), num(g.stat,'%.2f',false), pv(g.p)); end
        hp = '---';  if isfinite(g.holm_p), hp = pvm(g.holm_p); end
        add(sprintf('%s & %s & %s & %s & %s & %s \\\\', c1, qs{q,2}, e, tst, hp, g.sessions_agree));
    end
    if i < size(st4,1), add('\addlinespace'); end
end
add('\bottomrule', '\end{tabular}', '\end{table}', '');

% ---------------- Table: Fig 4G disturbance rejection ----------------------------------------
gs = R("4G_sess"); gn = R("4G_nested"); gm = R("4G_sessmed");
nt = regexp(gs.claim, '\((\d+) trials, (\d+) mice\)', 'tokens', 'once');
add('\begin{table}[!ht]', '\centering', '\small', ...
        sprintf('\\caption{\\textbf{Disturbance rejection} (Figure~\\ref{fig:figure4}G; %d sessions, %s mice, %s trials). $\\mathrm{RR}$, residual error energy relative to the disturbance; below one, the disturbance is rejected. All tests one-sided in the direction of rejection. Open versus closed loop, the same ratios computed on open-loop trials, compared across sessions with the Wilcoxon signed-rank test.}', ...
                gs.n, nt{2}, nt{1}), ...
        '\label{tab:stat_fig4g}', ...
        '\begin{tabular}{lcc}', '\toprule', ...
        'Measure & Estimate [95\% CI] & Test \\', '\midrule', ...
        sprintf('$\\mathrm{RR}$, session model (primary) & %s & $t(%s) = %s$, $p = %s$ \\\\', estci(gs.effect,gs.ci_lo,gs.ci_hi), dfs(gs.df), num(gs.stat,'%.2f',false), pv(gs.p)), ...
        sprintf('$\\mathrm{RR}$, mouse-nested model & %s & $t(%s) = %s$, $p = %s$ \\\\', estci(gn.effect,gn.ci_lo,gn.ci_hi), dfs(gn.df), num(gn.stat,'%.2f',false), pv(gn.p)), ...
        sprintf('Session median $\\mathrm{RR}$ (%s below one) & %s & $V = %d$, $p = %s$ \\\\', ...
                char(regexp(gm.claim,'\d+/\d+','match','once')), num(gm.effect), gm.stat, pv(gm.p)), ...
        '\addlinespace', '\multicolumn{3}{l}{\textit{Open versus closed loop (medians)}} \\');
oc = {'4G_olcl_RR','$\mathrm{RR}$'; '4G_olcl_offshare','Standing-offset share of residual'; '4G_olcl_RRfluct','Fluctuation energy / disturbance'};
for i = 1:size(oc,1)
    g = R(oc{i,1});
    clv = str2double(regexp(g.unit, 'CL ([\d.]+)', 'tokens', 'once'));
    ag  = regexp(g.claim, 'CL lower in (\d+/\d+)', 'tokens', 'once');
    add(sprintf('\\quad %s (lower in %s) & %s open, %s closed & $V = %d$, $p = %s$ \\\\', oc{i,2}, ag{1}, ...
        num(g.effect), num(clv), g.stat, pv(g.p)));
end
add('\bottomrule', '\end{tabular}', '\end{table}', '', '\clearpage   % flush the tables before the references');

    function add(varargin), L = [L, varargin]; end

fid = fopen(outFile, 'w');  fprintf(fid, '%s\n', L{:});  fclose(fid);
fprintf('[stats-tex] %d lines -> %s\n', numel(L), outFile);
end

% ---------------- formatting helpers ---------------------------------------------------------
function s = f3row(lab, g)
% one Fig 3 table row (session rule 2026-10-27); control windows carry the ratio and CI only
    nb = regexp(g.claim, '\((\d+/\d+) sessions <1', 'tokens', 'once');
    lw = sprintf('$%.0f$\\%%', 100*(1-g.effect) + 0);
    lw = strrep(lw, '$-0$', '$0$');
    if g.role == "control"
        s = sprintf('%s & %s & %s & --- & --- & --- & %s & --- \\\\', lab, ...
            estci(g.effect, g.ci_lo, g.ci_hi), lw, nb{1});
    else
        s = sprintf('%s & %s & %s & %s & %s & %s & %s (%s) & %s \\\\', lab, ...
            estci(g.effect, g.ci_lo, g.ci_hi), lw, num(g.stat), pvm(g.p), pvm(g.wilcoxon_p), ...
            nb{1}, g.mice_agree, pvm(g.lomo_worst_p));
    end
end
function s = num(x, f, mathmode)
    if nargin < 2 || isempty(f), f = '%.2f'; end
    if nargin < 3, mathmode = true; end
    s = sprintf(f, x);
    if strcmp(s, '-0.00'), s = '0.00'; end
    if mathmode, s = ['$' s '$']; end
end
function s = estci(e, lo, hi, signed)
    if nargin < 4, signed = false; end
    if signed, f = '%+.2f'; else, f = '%.2f'; end
    s = sprintf(['$' f '$ $[%.2f, %.2f]$'], e, lo, hi);
    s = regexprep(s, '^\$-0\.00\$', '\$0.00\$');     % no signed zero
    s = strrep(s, '[-0.00,', '[0.00,');  s = strrep(s, ', -0.00]', ', 0.00]');
end
function s = estrng(e, lo, hi)
% estimate with a min-max range (not a CI), e.g. per-session spread over 4 sessions
    s = sprintf('$%.2f$ $(%.2f$--$%.2f)$', e, lo, hi);
end
function s = pv(p)
    if isnan(p), s = '---'; return; end
    if p < 0.001
        ex = floor(log10(p)); m = p / 10^ex;
        if round(m,1) >= 10, m = m/10; ex = ex+1; end
        s = sprintf('%.1f\\times10^{%d}', m, ex);
    elseif p >= 0.1
        s = sprintf('%.2f', p);
    elseif p >= 0.01
        s = sprintf('%.3f', p);           % 2 significant figures, trailing zero kept (0.030)
    else
        s = sprintf('%.4f', p);
    end
end
function s = pctci(b, lo, hi, pct)
% log-scale estimate -> percent change; one decimal when the estimate is under 1 %
    if nargin < 4, pct = false; end
    v = 100*(exp([b lo hi]) - 1);
    if abs(v(1)) < 1, f = '%+.1f'; else, f = '%+.0f'; end
    u = '';  if pct, u = '\\%%'; end   % becomes \% after sprintf
    s = sprintf(['$' f '$' u ' $[%.0f, %.0f]$'], v(1), v(2), v(3));
end
function s = pvm(p)
    s = pv(p);  if ~strcmp(s,'---'), s = ['$' s '$']; end
end
function s = dfs(df)
    if abs(df - round(df)) < 0.05, s = sprintf('%d', round(df)); else, s = sprintf('%.1f', df); end
end
